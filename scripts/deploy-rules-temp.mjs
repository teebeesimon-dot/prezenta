import fs from "node:fs";
import crypto from "node:crypto";

const credentials = JSON.parse(process.env.FIREBASE_SERVICE_ACCOUNT || "{}");
const projectId = process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || credentials.project_id;
if (!credentials.client_email || !credentials.private_key || !projectId) throw new Error("Configurația Firebase este incompletă.");
const encode = (value) => Buffer.from(typeof value === "string" ? value : JSON.stringify(value)).toString("base64url");
const now = Math.floor(Date.now() / 1000);
const unsigned = `${encode({ alg: "RS256", typ: "JWT" })}.${encode({ iss: credentials.client_email, scope: "https://www.googleapis.com/auth/cloud-platform", aud: "https://oauth2.googleapis.com/token", iat: now, exp: now + 3600 })}`;
const signer = crypto.createSign("RSA-SHA256"); signer.update(unsigned);
const assertion = `${unsigned}.${signer.sign(credentials.private_key, "base64url")}`;
const tokenResponse = await fetch("https://oauth2.googleapis.com/token", { method: "POST", headers: { "content-type": "application/x-www-form-urlencoded" }, body: new URLSearchParams({ grant_type: "urn:ietf:params:oauth:grant-type:jwt-bearer", assertion }) });
if (!tokenResponse.ok) throw new Error(`Autentificarea Google a eșuat (${tokenResponse.status}).`);
const { access_token: token } = await tokenResponse.json();
const headers = { authorization: `Bearer ${token}`, "content-type": "application/json" };
const content = fs.readFileSync("firestore.rules", "utf8");
const rulesetResponse = await fetch(`https://firebaserules.googleapis.com/v1/projects/${projectId}/rulesets`, { method: "POST", headers, body: JSON.stringify({ source: { files: [{ name: "firestore.rules", content }] } }) });
const ruleset = await rulesetResponse.json();
if (!rulesetResponse.ok) throw new Error(`Crearea ruleset-ului a eșuat (${rulesetResponse.status}): ${ruleset.error?.message}`);
const releaseName = `projects/${projectId}/releases/cloud.firestore`;
const releaseResponse = await fetch(`https://firebaserules.googleapis.com/v1/${releaseName}`, { method: "PATCH", headers, body: JSON.stringify({ name: releaseName, rulesetName: ruleset.name }) });
const release = await releaseResponse.json();
if (!releaseResponse.ok) throw new Error(`Publicarea regulilor a eșuat (${releaseResponse.status}): ${release.error?.message}`);
console.log(`Reguli Firestore publicate: ${release.rulesetName}`);
